/**
 * Writes scripts/neon-setup.sql: one script to paste into Neon → SQL Editor that
 *  1. creates any tables that don't exist yet (every migration in /drizzle, made safe to re-run),
 *  2. adds the starting content to empty tables, and
 *  3. records the migrations as done, so `npm run db:migrate` on a PC later won't try to repeat them.
 *   npm run db:neon-sql
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { defaultFaqs, defaultPackages, defaultProjects, defaultSettings } from "./default-content";

const root = join(__dirname, "..");
const journal = JSON.parse(readFileSync(join(root, "drizzle/meta/_journal.json"), "utf8")) as { entries: { tag: string; when: number }[] };

const q = (s: string | null | undefined) => (s == null ? "NULL" : `'${s.replace(/'/g, "''")}'`);
const arr = (xs: string[]) => `ARRAY[${xs.map(q).join(", ")}]::text[]`;

/** Make generated CREATE statements safe to run twice. */
function idempotent(sql: string) {
  return sql
    .split("--> statement-breakpoint")
    .map((s) => s.trim())
    .filter(Boolean)
    .map((s) => {
      if (s.startsWith("CREATE TYPE")) return `DO $$ BEGIN\n  ${s.replace(/;$/, "")};\nEXCEPTION WHEN duplicate_object THEN NULL;\nEND $$;`;
      return s.replace(/^CREATE TABLE "/, 'CREATE TABLE IF NOT EXISTS "').replace(/^CREATE INDEX "/, 'CREATE INDEX IF NOT EXISTS "');
    })
    .join("\n\n");
}

const parts: string[] = [
  "-- Hexford Digital: database setup for Neon → SQL Editor.",
  "-- Safe to run more than once: it only creates what's missing and only fills empty tables.",
  "-- (Generated by `npm run db:neon-sql` — don't edit by hand.)",
  "",
];

for (const e of journal.entries) {
  parts.push(`-- ===== ${e.tag} =====`, idempotent(readFileSync(join(root, "drizzle", `${e.tag}.sql`), "utf8")), "");
}

parts.push("-- ===== Starting content (only if the table is empty) =====");
parts.push(
  `INSERT INTO "site_settings" ("key", "value")\nSELECT * FROM (VALUES\n${Object.entries(defaultSettings)
    .map(([k, v]) => `  (${q(k)}, ${q(v)})`)
    .join(",\n")}\n) AS v(key, value)\nWHERE NOT EXISTS (SELECT 1 FROM "site_settings");`,
);
parts.push(
  `INSERT INTO "packages" ("id", "name", "intro", "price", "badge", "items", "sort_order")\nSELECT * FROM (VALUES\n${defaultPackages
    .map((p) => `  (${q(p.id)}, ${q(p.name)}, ${q(p.intro)}, ${q(p.price)}, ${q(p.badge)}, ${arr(p.items)}, ${p.sortOrder})`)
    .join(",\n")}\n) AS v\nWHERE NOT EXISTS (SELECT 1 FROM "packages");`,
);
parts.push(
  `INSERT INTO "projects" ("name", "summary", "tags", "url", "image_url", "sort_order")\nSELECT * FROM (VALUES\n${defaultProjects
    .map((p) => `  (${q(p.name)}, ${q(p.summary)}, ${arr(p.tags)}, ${q(p.url)}, ${q(p.imageUrl)}, ${p.sortOrder})`)
    .join(",\n")}\n) AS v\nWHERE NOT EXISTS (SELECT 1 FROM "projects");`,
);
parts.push(
  `INSERT INTO "faqs" ("question", "answer", "sort_order")\nSELECT * FROM (VALUES\n${defaultFaqs
    .map((f) => `  (${q(f.question)}, ${q(f.answer)}, ${f.sortOrder})`)
    .join(",\n")}\n) AS v\nWHERE NOT EXISTS (SELECT 1 FROM "faqs");`,
);

parts.push("", "-- ===== Record the migrations as applied (matches drizzle-kit migrate) =====");
parts.push(
  'CREATE SCHEMA IF NOT EXISTS "drizzle";',
  'CREATE TABLE IF NOT EXISTS "drizzle"."__drizzle_migrations" (id SERIAL PRIMARY KEY, hash text NOT NULL, created_at bigint);',
);
for (const e of journal.entries) {
  const hash = createHash("sha256").update(readFileSync(join(root, "drizzle", `${e.tag}.sql`), "utf8")).digest("hex");
  parts.push(
    `INSERT INTO "drizzle"."__drizzle_migrations" ("hash", "created_at") SELECT '${hash}', ${e.when} WHERE NOT EXISTS (SELECT 1 FROM "drizzle"."__drizzle_migrations" WHERE "created_at" = ${e.when});`,
  );
}

writeFileSync(join(root, "scripts/neon-setup.sql"), parts.join("\n") + "\n");
console.log("Wrote scripts/neon-setup.sql");
